let failed = 0;
let checks = 0;
for (const c of cases) {
  const got = extractByHeuristics(c.text);
  for (const [k, v] of Object.entries(c.expect)) {
    checks++;
    const ok = typeof v === "function" ? Boolean(v(got[k])) : got[k] === v;
    if (!ok) failed++;
    console.log(
      `${ok ? "PASS" : "FAIL"} [${c.name}] ${k}: ${JSON.stringify(got[k])}` +
        (ok ? "" : ` (ожидалось ${typeof v === "function" ? "предикат" : JSON.stringify(v)})`)
    );
  }
}

(async () => {
  const sample = "Иванова Мария, 5 лет опыта. Навыки: SMM. Телефон: +7 900 111-22-33.";
  const viaApi = await extractStructuredData(sample);
  const viaHeur = extractByHeuristics(sample);
  const ok =
    JSON.stringify(viaApi) === JSON.stringify(viaHeur) &&
    viaApi.name === "Иванова Мария" &&
    viaApi.skills === "SMM" &&
    viaApi.education === "";
  checks++;
  if (!ok) failed++;
  console.log(
    `${ok ? "PASS" : "FAIL"} [async extractStructuredData без сервера] фолбэк на эвристику: ` +
      JSON.stringify(viaApi)
  );

  console.log(`\n${checks} проверок`);
  console.log(failed === 0 ? "ALL PASS" : `FAILED: ${failed}`);
  process.exit(failed === 0 ? 0 : 1);
})();
